function point(x,y)
	pset(x,y,11)
end

function line2(x1,y1,x2,y2)
	line(x1,y1,x2,y2,11)
end

function screen(x,y)
	local sx=(x+1)/2*128
	local sy=(1-(y+1)/2)*128
	return sx,sy
end

function project(x,y,z)
	return x/z,y/z
end

function translate_z(dz,x,y,z)
	return x,y,z+dz
end

function rotate_xz(angle,x,y,z)
	local c=cos(-angle)
	local s=sin(-angle)
	return x*c-z*s,y,x*s+z*c
end

