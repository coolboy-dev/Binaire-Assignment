function sortdice(hand)
  for i=1,#hand do
    local j=i
    while j>1 and hand[j-1]>hand[j] do
      hand[j],hand[j-1]=hand[j-1],hand[j]
      j-=1
    end
  end
end

function nested(outertable,target)
    local matches=0
    for _,innertable in pairs(outertable) do
        for _,val in pairs(innertable) do
            if val==target then
                matches+=1
            end
        end
    end
    return matches
end

function crypto(str)
    local res=""
    for i=1,#str do
        local b=sub(str,i,i)
        local c=ord(b)
        if c>=65 and c<=90 then
            res=res..chr(90-(c-65))
        elseif c>=97 and c<=122 then
            res=res..chr(122-(c-97))
        else
            res=res..b
        end
    end
    return res
end

