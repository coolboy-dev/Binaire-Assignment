function wraptext(str,limit)
  local words=split(str," ")
  local lines={}
  local currentline=""
  for w in all(words) do
    if #currentline+#w+1>limit then
      add(lines,currentline)
      currentline=w
    else
      if #currentline>0 then 
        currentline..=" "..w 
      else 
        currentline=w 
      end
    end
  end
  add(lines,currentline)
  return lines
end


